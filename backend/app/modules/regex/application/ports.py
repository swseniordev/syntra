"""Contratos requeridos por los casos de uso de Regex."""

from __future__ import annotations

from typing import Any, Protocol, Self

from app.modules.auditoria.application.ports import AuditWriter

Regex = dict[str, Any]


class RegexEvaluator(Protocol):
    def test(self, condition: str, flags: str, text: str) -> dict[str, Any]: ...


class RegexRepository(Protocol):
    def list(self, query: str, state: str, after_id: int | None, limit: int) -> tuple[int, list[Regex]]: ...
    def get(self, regex_id: int, *, for_update: bool = False) -> Regex | None: ...
    def lock_name(self, name: str) -> None: ...
    def name_exists(self, name: str, exclude_id: int | None = None) -> bool: ...
    def create(self, values: Regex, actor_id: int) -> Regex: ...
    def update(self, regex_id: int, values: Regex, actor_id: int) -> Regex: ...
    def versions(self, regex_id: int) -> list[dict[str, Any]]: ...


class RegexUnitOfWork(Protocol):
    regex: RegexRepository
    audit: AuditWriter
    def __enter__(self) -> Self: ...
    def __exit__(self, exc_type: object, exc_value: object, traceback: object) -> None: ...
    def commit(self) -> None: ...
