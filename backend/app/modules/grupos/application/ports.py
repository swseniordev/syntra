"""Contratos de persistencia y auditoría para grupos."""

from __future__ import annotations

from typing import Any, Protocol, Self

from app.modules.auditoria.application.ports import AuditWriter

Group = dict[str, Any]


class GroupRepository(Protocol):
    def lock_names(self) -> None: ...
    def list(self, query: str, state: str, after_id: int | None, limit: int) -> tuple[int, list[Group]]: ...
    def get(self, group_id: int, *, for_update: bool = False) -> Group | None: ...
    def name_exists(self, name: str, exclude_id: int | None = None) -> bool: ...
    def references_exist(self, user_ids: list[int], account_ids: list[int]) -> bool: ...
    def create(self, values: Group, actor_id: int) -> Group: ...
    def update(self, group_id: int, values: Group, actor_id: int) -> Group: ...


class GroupUnitOfWork(Protocol):
    groups: GroupRepository
    audit: AuditWriter
    def __enter__(self) -> Self: ...
    def __exit__(self, exc_type: object, exc_value: object, traceback: object) -> None: ...
    def commit(self) -> None: ...
