"""Contratos que usan los consumidores, sin adaptadores concretos."""

from typing import Protocol

from app.domain.tasks import ClaimedTask


class TaskConsumer(Protocol):
    def recover(self) -> int: ...
    def claim(self, worker_id: str) -> ClaimedTask | None: ...
    def process(self, task: ClaimedTask, worker_id: str) -> None: ...


class WorkerRegistry(Protocol):
    def register(self, worker_id: str, server: str, pid: int) -> None: ...
    def heartbeat(self, worker_id: str, active: int) -> None: ...
    def unregister(self, worker_id: str) -> None: ...


class Maintenance(Protocol):
    def cleanup(self) -> tuple[int, int]: ...


class MailProvider(Protocol):
    def send_password(self, recipient: str, password: str, timeout: float, reason: str = "alta") -> None: ...
